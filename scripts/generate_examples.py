def plain(value: str) -> str:
    value = re.sub(r"<[^>]+>", "", value)
    value = html.unescape(value)
    return re.sub(r"\s+", " ", value).strip()


def first_match(pattern: str, source: str, default: str = "") -> str:
    match = re.search(pattern, source, re.I | re.S)
    return plain(match.group(1)) if match else default


def client_for(filename: str) -> str:
    if "_codex_mcp" in filename:
        return "codex"
    if "_claude_mcp" in filename:
        return "claude"
    raise ValueError(f"Cannot determine client for {filename}")


def slug_for(filename: str) -> str:
    stem = re.sub(r"_(codex|claude)_mcp$", "", Path(filename).stem)
    return stem.replace("_", "-")


def category_for(filename: str, source: str, api_url: str, tools: list[str]) -> str:
    eyebrow = first_match(r'<span class="eyebrow">.*?·\s*([^<]+)</span>', source).lower()
    if len(tools) > 1 and filename in SPECIAL_TOOLS:
        return "workflows"
    aliases = {"document": "documents", "asset": "infra"}
    if eyebrow:
        value = aliases.get(eyebrow, eyebrow)
        if value in CATEGORY_NAMES:
            return value
    match = re.search(r"/api-reference/([^/]+)/", api_url)
    if match:
        value = aliases.get(match.group(1), match.group(1))
        if value in CATEGORY_NAMES:
            return value
    prefix = filename.split("_", 1)[0]
    return aliases.get(prefix, prefix) if aliases.get(prefix, prefix) in CATEGORY_NAMES else "workflows"


def extract_tools(filename: str, source: str) -> list[str]:
    structured = re.search(
        r"<strong>MCP tool</strong>\s*<br\s*/?>\s*<code>([^<]+)", source, re.I
    )
    if structured:
        return [plain(structured.group(1))]
    quoted = re.search(r"&quot;tool&quot;:\s*&quot;([^&]+)", source)
    if quoted:
        return [plain(quoted.group(1))]
    return SPECIAL_TOOLS.get(filename, [])


def extract_api_url(source: str) -> str:
    urls = re.findall(r'https://medux\.io/api-reference/[^"<\s]+', source)
    cleaned = []
    for url in urls:
        url = html.unescape(url).rstrip("/.,)")
        if url not in cleaned:
            cleaned.append(url)
    return cleaned[0] if cleaned else f"{SITE}/api-reference/"


def extract_prompt(filename: str, source: str, title: str, client: str) -> str:
    if filename in SPECIAL_PROMPTS:
        return SPECIAL_PROMPTS[filename]
    patterns = [
        r"<h2[^>]*>Prompt (?:Codex|Claude)</h2>.*?<pre><code>(.*?)</code>",
        r"<h2[^>]*>(?:Copyable |Example )?prompt[^<]*</h2>.*?<pre><code>(.*?)</code>",
        r"<pre><code>(.*?Use Medux.*?)</code>",
    ]
    for pattern in patterns:
        match = re.search(pattern, source, re.I | re.S)
        if match:
            candidate = plain(match.group(1))
            if 12 <= len(candidate) <= 1_500:
                return candidate
    action = re.sub(r"^How to\s+", "", title, flags=re.I)
    action = re.sub(r"\s+with (?:Codex|Claude) MCP and Medux$", "", action, flags=re.I)
    if client == "codex":
        return (
            f"Using the connected Medux MCP server, {action[0].lower() + action[1:]}. "
            "Inspect any required workspace files first. Show me the exact Medux tools "
            "and proposed arguments, then wait for my approval. After approval, monitor "
            "the task, save the result in this workspace, and verify the output."
        )
    return (
        f"Using the connected Medux tool, {action[0].lower() + action[1:]}. "
        "Use the attached inputs when required. Show me the exact Medux tools and proposed "
        "arguments, then wait for my approval. After approval, monitor the task and return "
        "the completed result."
    )


def extract_fields(source: str) -> list[dict[str, str]]:
    section = re.search(
        r"Request fields to review.*?<tbody>(.*?)</tbody>", source, re.I | re.S
    )
    if not section:
        return []
    fields = []
    for row in re.findall(r"<tr>(.*?)</tr>", section.group(1), re.I | re.S):
        cells = [plain(cell) for cell in re.findall(r"<td>(.*?)</td>", row, re.I | re.S)]
        if len(cells) >= 4:
            fields.append(
                {"name": cells[0], "type": cells[1], "requirement": cells[2], "purpose": cells[3]}
            )
    return fields[:16]


def extract_description(source: str) -> str:
    return first_match(r'<meta name="description" content="([^"]+)', source)


def tutorial_record(path: Path, repo: Path) -> dict:
    source = path.read_text(encoding="utf-8", errors="ignore")
    filename = path.name
    client = client_for(filename)
    title = first_match(r"<title>([^<]+)</title>", source, path.stem)
    tools = extract_tools(filename, source)
    api_url = extract_api_url(source)
    category = category_for(filename, source, api_url, tools)
    slug = slug_for(filename)
    manual_path = MANUAL_EXAMPLES.get(filename)
    output = manual_path or f"examples/{client}/{category}/{slug}/README.md"
    return {
        "tutorial_file": filename,
        "tutorial_url": f"{SITE}/tutorials/{filename}",
        "client": client,
        "category": category,
        "slug": slug,
        "title": title,
        "description": extract_description(source),
        "tools": tools,
        "api_url": api_url,
        "fields": extract_fields(source),
        "prompt": extract_prompt(filename, source, title, client),
        "additional_api_urls": SPECIAL_EXTRA_API_URLS.get(filename, []),
        "example_path": output,
        "mode": "manual" if manual_path else "generated",
    }


def tool_label(tools: list[str]) -> str:
    return ", ".join(f"`{tool}`" for tool in tools) if tools else "Live Medux MCP schema"


def render_example(record: dict) -> str:
    client_name = "Codex" if record["client"] == "codex" else "Claude"
    lines = [
        GENERATED_MARKER,
        f"# {record['title']}",
        "",
        record["description"] or f"Run this Medux workflow with {client_name} through MCP.",
        "",
        "## Expected Medux tools",
        "",
    ]
    if record["tools"]:
        lines.extend(f"- `{tool}`" for tool in record["tools"])
    else:
        lines.append("- Inspect the live Medux MCP schema; this tutorial does not publish a stable tool identifier.")
    lines.extend(["", "## Prompt", "", "```text", record["prompt"], "```", "", "## Review before approval", ""])
    if record["fields"]:
        for field in record["fields"]:
            requirement = field["requirement"].lower()
            purpose = field["purpose"].rstrip(".")
            lines.append(f"- `{field['name']}` ({requirement}): {purpose}.")
    else:
        lines.extend(
            [
                "- Every local file or attachment maps to the intended Medux file or asset ID.",
                "- The proposed tool names match the live Medux MCP schema.",
                "- Operation order, output settings, and cost-relevant options match the request.",
            ]
        )
    lines.extend(["", f"## {client_name} notes", ""])
    if record["client"] == "codex":
        lines.extend(
            [
                "- Use `/mcp` to confirm that Medux and the expected tools are available.",
                "- Workspace paths must point to the intended local inputs and output directory.",
                "- Review any network, shell, or filesystem approval requested during upload, download, or verification.",
            ]
        )
    else:
        lines.extend(
            [
                "- In claude.ai or Claude Desktop, attach inputs and enable the Medux connector for the conversation.",
                "- In Claude Code, keep inputs in the working directory and confirm Medux with `/mcp`.",
                "- An attachment is not a Medux `file_id`; approve the upload step when the workflow requires one.",
            ]
        )
    lines.extend(
        [
            "",
            "## Learn more",
            "",
            f"- [Complete {client_name} tutorial]({record['tutorial_url']})",
            f"- [Matching API reference]({record['api_url']})",
            *[f"- [Additional API reference]({url})" for url in record["additional_api_urls"]],
            "- [Medux MCP overview](https://medux.io/overview/mcp)",
            "",
            "## Verification",
            "",
            "Status: **Documentation-derived**. See the repository [verification policy](../../../../docs/verification.md).",
            "",
        ]
    )
    return "\n".join(lines)


def render_index(client: str, records: list[dict]) -> str:
    client_name = "Codex" if client == "codex" else "Claude"
    grouped = defaultdict(list)
    for record in records:
        grouped[record["category"]].append(record)
    lines = [GENERATED_MARKER, f"# Medux MCP examples for {client_name}", ""]
    lines.append(f"{len(records)} workflows derived from published Medux {client_name} tutorials.")
    lines.extend(["", "All entries are documentation-derived unless their directory contains a `VERIFICATION.md` record.", ""])
    for category in sorted(grouped, key=lambda item: CATEGORY_NAMES.get(item, item)):
        lines.extend([f"## {CATEGORY_NAMES.get(category, category.title())}", "", "| Example | Expected tool |", "| --- | --- |"])
        for record in sorted(grouped[category], key=lambda item: item["title"].lower()):
            index_path = Path(f"examples/{client}/INDEX.md")
            relative = Path(record["example_path"]).relative_to(index_path.parent)
            lines.append(f"| [{record['title']}]({relative.as_posix()}) | {tool_label(record['tools'])} |")
        lines.append("")
    return "\n".join(lines)


def remove_stale_generated(repo: Path, expected: set[Path]) -> None:
    for path in (repo / "examples").rglob("README.md"):
        if path in expected:
            continue
        try:
            head = path.read_text(encoding="utf-8", errors="ignore")[:120]
        except OSError:
            continue
        if GENERATED_MARKER in head:
            path.unlink()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tutorial-dir", type=Path, required=True)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--expected-count", type=int)
    args = parser.parse_args()
    repo = args.repo.resolve()
    tutorials = args.tutorial_dir.resolve()

    pages = sorted(path for path in tutorials.glob("*.html") if path.name != "index.html")
    records = [tutorial_record(path, repo) for path in pages]
    if args.expected_count is not None and len(records) != args.expected_count:
        raise SystemExit(f"Expected {args.expected_count} tutorial pages, found {len(records)}")
    if any(not record["tools"] for record in records):
        missing = [record["tutorial_file"] for record in records if not record["tools"]]
        raise SystemExit(f"Missing tool mappings: {missing}")

    expected = set()
    for record in records:
        output = repo / record["example_path"]
        expected.add(output)
        if record["mode"] == "generated":
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(render_example(record), encoding="utf-8")
        elif not output.exists():
            raise SystemExit(f"Manual example missing: {output}")
    remove_stale_generated(repo, expected)

    for client in ("codex", "claude"):
        subset = [record for record in records if record["client"] == client]
        (repo / f"examples/{client}/INDEX.md").write_text(render_index(client, subset), encoding="utf-8")

    manifest = {
        "source": "Published Medux tutorial HTML supplied to the generator",
        "tutorial_count": len(records),
        "clients": dict(Counter(record["client"] for record in records)),
        "records": records,
    }
    (repo / "examples/manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"Generated {sum(r['mode'] == 'generated' for r in records)} examples; preserved {sum(r['mode'] == 'manual' for r in records)} manual examples.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
